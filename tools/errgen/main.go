// errgen generates the per-operation error types of agentbus from errors.json.
//
// For every operation it writes a cause enum (one constant per possible failure, documented), the error type
// alias OpError[<Op>Cause] and the tables behind the opCause interface. A "Storage" cause is added to every
// operation unless it sets "noStorage": the shared state can always fail to load or save.
//
//	go run . -spec ../../agentbus/errors.json -out ../../agentbus/errors_gen.go
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strings"
)

// spec is the content of errors.json.
type spec struct {
	Operations []operation `json:"operations"` // in output order
}

// operation describes one MCP tool or CLI subcommand.
type operation struct {
	Type      string  `json:"type"`      // Go name prefix, e.g. "QuizStart" → QuizStartCause, QuizStartError
	Op        string  `json:"op"`        // tool or subcommand name, e.g. "quiz_start"
	What      string  `json:"what"`      // short description used in comments, e.g. "the MCP tool quiz_start"
	NoStorage bool    `json:"noStorage"` // true: the operation never touches the shared state
	Causes    []cause `json:"causes"`    // the possible failures (Storage is appended automatically)
}

// cause is one possible failure of an operation.
type cause struct {
	Name  string `json:"name"`  // constant suffix, e.g. "NotCoordinator"
	Class string `json:"class"` // ErrorClass name without the prefix, e.g. "Permission"
	Doc   string `json:"doc"`   // when it happens
}

// validClasses are the ErrorClass names of agentbus/errors.go.
var validClasses = map[string]bool{
	"InvalidArgument": true, "NotFound": true, "NotInTeam": true, "Permission": true, "Conflict": true,
	"InvalidState": true, "Storage": true, "UnknownTool": true, "Process": true,
}

// main reads the spec, validates it and writes the generated, gofmt-ed file.
func main() {
	specPath := flag.String("spec", "errors.json", "specification file")
	outPath := flag.String("out", "errors_gen.go", "output file")
	flag.Parse()
	data, err := os.ReadFile(*specPath)
	if err != nil {
		fail("cannot read the spec: %v", err)
	}
	var sp spec
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&sp); err != nil {
		fail("cannot decode %s: %v", *specPath, err)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/errgen from errors.json; DO NOT EDIT.\n\npackage main\n")
	seen := map[string]bool{}
	for _, op := range sp.Operations {
		if op.Type == "" || op.Op == "" || op.What == "" {
			fail("operation %+v: type, op and what are required", op)
		}
		if seen[op.Type] {
			fail("operation type %s is defined twice", op.Type)
		}
		seen[op.Type] = true
		causes := op.Causes
		if !op.NoStorage {
			causes = append(causes, cause{Name: "Storage", Class: "Storage", Doc: "the shared state or a file could not be read or written"})
		}
		names := map[string]bool{}
		for _, c := range causes {
			if !validClasses[c.Class] {
				fail("%s.%s: unknown class %q", op.Type, c.Name, c.Class)
			}
			if c.Name == "" || c.Doc == "" || names[c.Name] {
				fail("%s: cause %q needs a unique name and a doc", op.Type, c.Name)
			}
			names[c.Name] = true
		}
		writeOperation(&b, op, causes)
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		fail("generated code does not compile: %v\n%s", err, b.String())
	}
	// generated Go source is read by the toolchain and humans like every other source file
	if err := os.WriteFile(*outPath, out, 0o644); err != nil { //nolint:gosec // G306: source files are world-readable
		fail("cannot write %s: %v", *outPath, err)
	}
}

// writeOperation writes the enum, the error alias and the opCause methods of one operation.
func writeOperation(b *bytes.Buffer, op operation, causes []cause) {
	ct := op.Type + "Cause"
	table := strings.ToLower(op.Type[:1]) + op.Type[1:] + "Causes"
	fmt.Fprintf(b, "\n// ---------------------------------------------------------------- %s\n\n", op.Op)
	fmt.Fprintf(b, "// %s is a reason why %s failed.\ntype %s int\n\nconst (\n", ct, op.What, ct)
	for i, c := range causes {
		if i == 0 {
			fmt.Fprintf(b, "\t%s%s %s = iota // %s [%s]\n", op.Type, c.Name, ct, c.Doc, c.Class)
		} else {
			fmt.Fprintf(b, "\t%s%s // %s [%s]\n", op.Type, c.Name, c.Doc, c.Class)
		}
	}
	b.WriteString(")\n\n")
	fmt.Fprintf(b, "// %sError is the error of %s.\ntype %sError = OpError[%s]\n\n", op.Type, op.What, op.Type, ct)
	fmt.Fprintf(b, "// %s describes the %s values (same order as the constants).\nvar %s = [...]causeInfo{\n", table, ct, table)
	for _, c := range causes {
		fmt.Fprintf(b, "\t{%q, Class%s},\n", c.Name, c.Class)
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(b, "// op implements opCause.\nfunc (%s) op() string { return %q }\n\n", ct, op.Op)
	fmt.Fprintf(b, "// info implements opCause.\nfunc (c %s) info() causeInfo { return %s[c] }\n\n", ct, table)
	fmt.Fprintf(b, "// String returns the cause name.\nfunc (c %s) String() string { return c.info().name }\n", ct)
}

// fail prints an error and exits.
func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "errgen: "+format+"\n", args...)
	os.Exit(1)
}
